/// <summary>
/// Mapeo de la factura a la plantilla con el motor real: plazo, instrucciones de pago y pie de los
/// ajustes de facturación, y que un payload viejo sin esas claves salga igual que antes.
/// </summary>
public sealed class ProcessInvoiceGenerationHandlerTests
{
    private static readonly Guid Tenant = Guid.NewGuid();

    [Fact]
    public async Task Terms_and_instructions_are_printed_and_the_invoice_footer_wins_over_the_branding()
    {
        var html = await RenderAsync(
            Payload() with
            {
                PaymentTerms = "Net 30",
                PaymentInstructions = "Zelle to pay@office.com\nor check to <Office>",
                InvoiceFooter = "Thank you & see you\nnext season",
            },
            new BrandingPayload(FooterText: "Branding footer")
        );

        Assert.Contains("Terms: Net 30", html);
        Assert.Contains("Payment instructions", html);
        Assert.Contains("or check to &lt;Office&gt;", html);
        Assert.Contains("Thank you &amp; see you<br />next season", html);
        Assert.DoesNotContain("Branding footer", html);
        Assert.DoesNotContain("Document generated by", html);
    }

    [Fact]
    public async Task Without_an_invoice_footer_the_branding_footer_is_used()
    {
        var html = await RenderAsync(Payload(), new BrandingPayload(FooterText: "Branding footer"));

        Assert.Contains("<div class=\"footer\">Branding footer</div>", html);
    }

    [Fact]
    public async Task An_old_payload_renders_as_before()
    {
        var html = await RenderAsync(Payload(), null);

        Assert.Contains("<div class=\"footer\">Document generated by TaxOffix · Invoice INV-2026-00042</div>", html);
        Assert.DoesNotContain("Terms:", html);
        Assert.DoesNotContain("<div class=\"instructions\">", html);
    }

    [Fact]
    public async Task Payment_instructions_are_hidden_on_a_paid_invoice()
    {
        var html = await RenderAsync(Payload() with { Status = "Paid", PaymentInstructions = "Zelle" }, null);

        Assert.DoesNotContain("<div class=\"instructions\">", html);
    }

    private static InvoicePayload Payload() =>
        new(
            "USD",
            new DateOnly(2026, 11, 3),
            new DateOnly(2026, 12, 3),
            new InvoiceParty("Gutierrez Tax LLC", "12-3456789", null),
            new InvoiceParty("Client", "", null),
            [new InvoiceLine("Tax prep", 1, 350m, 350m)],
            350m,
            0m,
            350m,
            null
        );

    private static async Task<string> RenderAsync(InvoicePayload invoice, BrandingPayload? branding)
    {
        var generation = NewRequested();
        var renderer = new CapturingRenderer();

        await ProcessInvoiceGenerationHandler.Handle(
            new ProcessInvoiceGenerationCommand(
                generation.Id,
                Tenant,
                "INV-2026-00042",
                "billing.invoice.v1",
                1,
                "Invoice",
                generation.Owner.OwnerId,
                1,
                2026,
                "invoice.pdf",
                "corr",
                invoice,
                branding
            ),
            new SingleGeneration(generation),
            new NoBranding(),
            new NoLogo(),
            renderer,
            new StopAfterRender(),
            new UnusedStorage(),
            new NoQr(),
            new NoopUnitOfWork(),
            new RecordingBus(),
            new NoopCorrelation(),
            TimeProvider.System,
            TestPlatform.Settings,
            NullLogger<ProcessInvoiceGenerationCommand>.Instance,
            CancellationToken.None
        );

        return Assert.IsType<string>(renderer.Html);
    }

    [Fact]
    public async Task The_handler_publishes_SaveFileRequested_after_saving_the_upload_state()
    {
        var generation = NewRequested();
        var bus = new RecordingBus();
        var unitOfWork = new CountingUnitOfWork();

        await ProcessAsync(generation, new AcceptingStorage(), bus, unitOfWork);

        var save = Assert.Single(bus.Published.OfType<SaveFileRequestedIntegrationEvent>());
        Assert.Equal(Tenant, save.TenantId);
        Assert.Equal(generation.FileId, save.FileId);
        Assert.Equal("documents", save.RequestingService);
        Assert.Equal("temp-bucket", save.SourceBucket);
        Assert.Equal($"documents/{save.FileId:N}/invoice.pdf", save.SourceObjectKey);
        Assert.Equal("Invoice", save.OwnerType);
        Assert.Equal(generation.Owner.OwnerId, save.OwnerId);
        Assert.Equal("Invoices", save.FolderType);
        Assert.Equal(2026, save.TaxYear);
        Assert.Equal("invoice.pdf", save.OriginalName);
        Assert.Equal("application/pdf", save.ContentType);
        Assert.Equal(4, save.SizeBytes);
        Assert.Equal(DocumentGenerationStatus.Uploading, generation.Status);
        Assert.True(unitOfWork.Saves > 0);
    }

    [Fact]
    public async Task A_failed_upload_fails_the_generation_and_asks_nothing_of_CloudStorage()
    {
        var generation = NewRequested();
        var bus = new RecordingBus();

        await ProcessAsync(generation, new RefusingStorage(), bus, new CountingUnitOfWork());

        Assert.Empty(bus.Published.OfType<SaveFileRequestedIntegrationEvent>());
        Assert.Single(bus.Published.OfType<DocumentGenerationFailedIntegrationEvent>());
        Assert.Equal(DocumentGenerationStatus.Failed, generation.Status);
    }

    private static Task ProcessAsync(
        DocumentGeneration generation,
        IDocumentStorageClient storage,
        RecordingBus bus,
        IUnitOfWork unitOfWork
    ) =>
        ProcessInvoiceGenerationHandler.Handle(
            new ProcessInvoiceGenerationCommand(
                generation.Id,
                Tenant,
                "INV-2026-00042",
                "billing.invoice.v1",
                1,
                "Invoice",
                generation.Owner.OwnerId,
                1,
                2026,
                "invoice.pdf",
                "corr",
                Payload(),
                null
            ),
            new SingleGeneration(generation),
            new NoBranding(),
            new NoLogo(),
            new CapturingRenderer(),
            new TinyPdf(),
            storage,
            new NoQr(),
            unitOfWork,
            bus,
            new NoopCorrelation(),
            TimeProvider.System,
            TestPlatform.Settings,
            NullLogger<ProcessInvoiceGenerationCommand>.Instance,
            CancellationToken.None
        );

    private sealed class TinyPdf : IHtmlToPdfConverter
    {
        public Task<Result<byte[]>> ConvertAsync(string html, CancellationToken ct = default) =>
            Task.FromResult(Result.Success(new byte[] { 0x25, 0x50, 0x44, 0x46 }));
    }

    private sealed class AcceptingStorage : IDocumentStorageClient
    {
        public Task<Result<StorageUploadResult>> UploadAsync(
            Guid fileId,
            byte[] content,
            string fileName,
            string contentType,
            CancellationToken ct = default
        ) =>
            Task.FromResult(
                Result.Success(
                    new StorageUploadResult(
                        fileId,
                        "temp-bucket",
                        $"documents/{fileId:N}/{fileName}",
                        content.LongLength,
                        contentType
                    )
                )
            );
    }

    private sealed class RefusingStorage : IDocumentStorageClient
    {
        public Task<Result<StorageUploadResult>> UploadAsync(
            Guid fileId,
            byte[] content,
            string fileName,
            string contentType,
            CancellationToken ct = default
        ) => Task.FromResult(Result.Failure<StorageUploadResult>(new Error("Documents.Storage.Upload", "Refused.")));
    }

    private sealed class CountingUnitOfWork : IUnitOfWork
    {
        public int Saves { get; private set; }

        public Task<int> SaveChangesAsync(CancellationToken ct = default)
        {
            Saves++;
            return Task.FromResult(1);
        }
    }

    private static DocumentGeneration NewRequested() =>
        DocumentGeneration
            .Request(
                tenantId: Tenant,
                documentType: DocumentType.Create("Invoice").Value,
                templateKey: TemplateKey.Create("billing.invoice.v1").Value,
                templateVersion: 1,
                outputFormat: DocumentOutputFormat.Pdf,
                owner: new GenerationOwner("Invoice", Guid.NewGuid()),
                sourceService: "billing",
                documentVersion: 1,
                priority: DocumentPriority.Normal,
                idempotencyKey: Guid.NewGuid().ToString("N"),
                correlationId: "corr",
                causationId: null,
                nowUtc: DateTime.UtcNow
            )
            .Value;

    // Renderiza con el motor real y guarda el HTML; el PDF se corta después (no hace falta Chromium).
    private sealed class CapturingRenderer : IDocumentTemplateRenderer
    {
        private readonly TemplateDocumentRenderer real = new(NullLogger<TemplateDocumentRenderer>.Instance);

        public string? Html { get; private set; }

        public async Task<Result<string>> RenderHtmlAsync(
            string templateKey,
            int templateVersion,
            Guid tenantId,
            IReadOnlyDictionary<string, object?> data,
            CancellationToken ct = default
        )
        {
            var result = await real.RenderHtmlAsync(templateKey, templateVersion, tenantId, data, ct);
            Html = result.IsSuccess ? result.Value : null;
            return result;
        }
    }

    private sealed class StopAfterRender : IHtmlToPdfConverter
    {
        public Task<Result<byte[]>> ConvertAsync(string html, CancellationToken ct = default) =>
            Task.FromResult(Result.Failure<byte[]>(new Error("Test.Stop", "Stop after rendering.")));
    }

