    public static IReadOnlyCollection<NotificationCatalogEntry> All { get; } = Entries.Values.ToArray();

    public static bool TryGet(string kind, out NotificationCatalogEntry? entry) => Entries.TryGetValue(kind, out entry);

    public static NotificationCatalogEntry GetRequired(string kind) =>
        Entries.TryGetValue(kind, out var entry)
            ? entry
            : throw new KeyNotFoundException($"Notification kind '{kind}' is not registered.");

    private static NotificationCatalogEntry Entry(
        string kind,
        NotificationCatalogCategory category,
        NotificationPriority priority,
        NotificationRecipientPolicy recipientPolicy,
        IReadOnlySet<NotificationChannel> channels,
        bool isMandatory,
        string resourceType,
        NotificationAction action
    ) =>
        new(
            kind,
            category,
            priority,
            recipientPolicy,
            channels,
            isMandatory,
            $"notif.{kind}.title",
            $"notif.{kind}.body",
            Enum.Parse<NotificationResourceType>(resourceType.Replace("_", string.Empty), true),
            action
        );

    private static IReadOnlySet<NotificationChannel> Channels(params NotificationChannel[] channels) =>
        channels.ToFrozenSet();
